const DARK_VARIANTS: Partial<Record<ChatFileIconId, ChatFileIconId>> = {
  next: "next-dark",
  rust: "rust-dark"
};

/**
 * Resolves a recognizable local icon for a workspace file.
 *
 * Exact filenames and tool configuration names take precedence over compound
 * suffixes and ordinary extensions. The comparison is case-insensitive.
 *
 * @param filePath Workspace-relative or absolute file path.
 * @returns Local icon identifiers for the active color mode.
 */
export function chatFilePresentation(filePath: string): ChatFilePresentation {
  const normalizedPath = filePath.replaceAll("\\", "/").toLowerCase();
  const name = normalizedPath.split("/").at(-1) ?? normalizedPath;
  const exact = EXACT_FILE_ICONS[name];
  if (exact) return presentation(exact);

  const named = namedFileIcon(name);
  if (named) return presentation(named);

  for (const [stem, icon] of CONFIG_STEM_ICONS) {
    if (name === stem || name.startsWith(`${stem}.`)) return presentation(icon);
  }

  if (name.endsWith(".d.ts")) return presentation("typescript-definition");
  if (/\.(?:test|spec)\.tsx$/.test(name)) return presentation("react");
  if (/\.(?:test|spec)\.(?:ts|mts|cts)$/.test(name)) return presentation("typescript-test");
  if (/\.(?:test|spec)\.(?:js|mjs|cjs)$/.test(name)) return presentation("javascript-test");

  const extension = name.includes(".") ? name.split(".").at(-1) ?? "" : "";
  return presentation(EXTENSION_ICONS[extension] ?? "default");
}

function namedFileIcon(name: string): ChatFileIconId | undefined {
  if (name === "containerfile" || name.startsWith("dockerfile.")) return "docker";
  if (name === "license" || name === "licence" || /^licen[cs]e[._-]/.test(name)) return "license";
  if (name === "readme" || name.startsWith("readme.")) return "markdown";
  if (name === "changelog" || name.startsWith("changelog.")) return "markdown";
  if (name === ".env" || name.startsWith(".env.")) return "dotenv";
  if (name.startsWith("requirements") && name.endsWith(".txt")) return "python";
  if (name === "tsconfig.json" || name === "jsconfig.json" || /^tsconfig\..+\.json$/.test(name)) {
    return "typescript-config";
  }
  if (/^\.eslint(?:rc)?(?:\.|$)/.test(name)) return "eslint";
  if (/^\.prettier(?:rc)?(?:\.|$)/.test(name)) return "prettier";
  if (/^\.stylelint(?:rc)?(?:\.|$)/.test(name)) return "stylelint";
  if (name.endsWith(".lock")) return "package";
  return undefined;
}

function presentation(icon: ChatFileIconId): ChatFilePresentation {
  const darkIcon = DARK_VARIANTS[icon];
  return darkIcon ? { icon, darkIcon } : { icon };
}
